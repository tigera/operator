var _ = Describe("filterDistrustedCertificates", func() {
	var otherRoot string

	BeforeEach(func() {
		key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		Expect(err).NotTo(HaveOccurred())
		tmpl := &x509.Certificate{
			SerialNumber:          big.NewInt(1),
			Subject:               pkix.Name{CommonName: "Other Root CA"},
			NotBefore:             time.Now(),
			NotAfter:              time.Now().Add(time.Hour),
			IsCA:                  true,
			BasicConstraintsValid: true,
		}
		der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
		Expect(err).NotTo(HaveOccurred())
		otherRoot = string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}))
	})

	for name, root := range emSignRoots {
		It("drops "+name+" and keeps the other roots", func() {
			bundle := "# " + name + "\n" + root + "\n# Other Root CA\n" + otherRoot

			filtered := certificatemanagement.FilterDistrustedCertificates([]byte(bundle))

			Expect(string(filtered)).NotTo(ContainSubstring("emSign"))
			Expect(commonNames(filtered)).To(Equal([]string{"Other Root CA"}))
		})
	}

	It("returns the bundle byte for byte when it holds no distrusted root", func() {
		bundle := []byte("# Other Root CA\n" + otherRoot + "\n")
		Expect(certificatemanagement.FilterDistrustedCertificates(bundle)).To(Equal(bundle))
	})

	It("returns nothing for an empty bundle", func() {
		Expect(certificatemanagement.FilterDistrustedCertificates(nil)).To(BeNil())
	})
})

func commonNames(bundle []byte) []string {
	var names []string
	for {
		var block *pem.Block
		block, bundle = pem.Decode(bundle)
		if block == nil {
			return names
		}
		cert, err := x509.ParseCertificate(block.Bytes)
		Expect(err).NotTo(HaveOccurred())
		names = append(names, cert.Subject.CommonName)
	}
}
